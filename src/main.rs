use serde::{Serialize, Deserialize};
use std::path::PathBuf;
use std::collections::HashMap;

#[derive(Serialize, Deserialize)]
struct Wallpaper {
	pub comment: String,
	pub override_auto: bool,
    pub current: PathBuf,
    pub available: Vec<PathBuf>,
    pub auto: HashMap<String, u32>,
}	
impl Wallpaper {
	fn gen_default() -> Wallpaper {
		let default = Wallpaper { comment: "DON'T EDIT THIS MANUALLY. THIS IS GENERATED BY THE chlebqowy-wallpaper-select APP".to_string(),
			override_auto: false,
			current: "/usr/share/chlebqowy-wallpaper-select/default.png".into(), 
			available: vec![],
			auto: HashMap::new()
		}; 
		return default;
	}
	fn create_json(_err: std::io::Error) -> String {
		let default: Wallpaper = Self::gen_default();
		//println!("2");
		let wallpaper_json: String = serde_json::to_string(&default).unwrap();
		//println!("{}", wallpaper_json);
		let _ = std::fs::write("wallpaper.json", &wallpaper_json);
		//println!("2.2");
		return wallpaper_json;
	}
	pub fn load() -> Wallpaper {
		let wallpaper_file = std::fs::read_to_string("wallpaper.json");
		//println!("1");
		let wallpaper: Wallpaper = serde_json::from_str(
			&wallpaper_file.unwrap_or_else(Self::create_json)
		).unwrap(); // TODO make it display an error message when that's implemented	
		//println!("3");
		return wallpaper;
	}
}
impl Default for Wallpaper {
	fn default() -> Self {
		Wallpaper::load()
	}
}
	
fn main() {
	Wallpaper::load();
}
